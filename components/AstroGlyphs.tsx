/**
 * A single glyph, sized and colored by the caller. Accessible by default:
 * the ASCII source character (e.g. "Q") is never exposed to assistive tech,
 * only GLYPH_LABELS' human-readable name (e.g. "Sun") via role="img" and a
 * nested <title>.
 */
export function AstroGlyph({
  name,
  size = 16,
  color = "currentColor",
  className,
  title,
}: {
  name: GlyphName;
  size?: number;
  color?: string;
  className?: string;
  /** Overrides the default accessible label (e.g. to say "Sun retrograde"
   * instead of just "Sun") without needing a whole new glyph variant. */
  title?: string;
}) {
  const label = title ?? GLYPH_LABELS[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 1 1"
      role="img"
      aria-label={label}
      className={className}
      style={{ display: "inline-block", verticalAlign: "middle", flexShrink: 0 }}
    >
      <title>{label}</title>
      <use href={`#glyph-${name}`} width={1} height={1} fill={color} />
    </svg>
  );
}
